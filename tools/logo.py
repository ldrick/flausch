#!/usr/bin/env python3
"""Generates the Flausch wordmark: "Flausch" in Montez (ui/fonts, Apache 2.0) as vector paths.

Writes
- logo/flausch.svg: the wordmark in pink (README)
- android/res/drawable/ic_launcher_foreground.xml: monochrome themed launcher icon
The app sets the same text with the bundled font (Theme.font-logo); the colored launcher icon and the store icon
(the wordmark embroidered on knit) come from tools/knit.py.

Needs fonttools: python3 tools/logo.py
"""

from pathlib import Path

from fontTools.pens.boundsPen import BoundsPen
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen
from fontTools.ttLib import TTFont

ROOT = Path(__file__).resolve().parent.parent
FONT = ROOT / "ui/fonts/Montez-Regular.ttf"
TEXT = "Flausch"
PINK = "#DF7FA5"  # Theme.accent (light)
WIDTH = 0.62  # width of the wordmark in the 108dp adaptive icon, as in tools/knit.py
BOLD = 1.5  # outline in dp, as thick as the yarn in tools/knit.py (BOLD there)


def outline():
    """Path data of TEXT with the baseline at y=0 (y down), and its bounding box (x0, y0, x1, y1)."""
    font = TTFont(FONT)
    glyphs = font.getGlyphSet()
    cmap = font.getBestCmap()
    pen = SVGPathPen(glyphs, lambda v: f"{v:.1f}".rstrip("0").rstrip("."))
    bounds = BoundsPen(glyphs)
    x = 0
    for ch in TEXT:
        glyph = glyphs[cmap[ord(ch)]]
        for target in (pen, bounds):
            glyph.draw(TransformPen(target, (1, 0, 0, -1, x, 0)))
        x += glyph.width
    return pen.getCommands(), bounds.bounds


def svg():
    data, (x0, y0, x1, y1) = outline()
    pad = (y1 - y0) * 0.05
    w, h = x1 - x0 + 2 * pad, y1 - y0 + 2 * pad
    return f"""<svg xmlns="http://www.w3.org/2000/svg" width="{w / 10:.0f}" height="{h / 10:.0f}" viewBox="{x0 - pad:.0f} {y0 - pad:.0f} {w:.0f} {h:.0f}">
  <!-- Generated by tools/logo.py: "{TEXT}" in Montez (Apache 2.0). -->
  <path fill="{PINK.lower()}" d="{data}"/>
</svg>
"""


def vector():
    data, (x0, y0, x1, y1) = outline()
    scale = 108 * WIDTH / (x1 - x0)
    tx = 54 - (x0 + x1) / 2 * scale
    ty = 54 - (y0 + y1) / 2 * scale
    return f"""<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by tools/logo.py. Monochrome themed launcher icon: "{TEXT}" in Montez (Apache 2.0). -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="108dp"
    android:height="108dp"
    android:viewportWidth="108"
    android:viewportHeight="108">
    <group
        android:scaleX="{scale:.5f}"
        android:scaleY="{scale:.5f}"
        android:translateX="{tx:.3f}"
        android:translateY="{ty:.3f}">
        <path
            android:fillColor="{PINK}"
            android:strokeColor="{PINK}"
            android:strokeWidth="{BOLD / scale:.2f}"
            android:strokeLineJoin="round"
            android:pathData="{data}" />
    </group>
</vector>
"""


if __name__ == "__main__":
    (ROOT / "logo/flausch.svg").write_text(svg())
    (ROOT / "android/res/drawable/ic_launcher_foreground.xml").write_text(vector())
