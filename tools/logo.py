#!/usr/bin/env python3
"""Generates the nøste logo, a ball of yarn with cut-out wraps and a loose end, in mint.

Single source for:
- ui/icons/logo.svg: in the app (colorized with Theme.accent) and in the README
- android/res/drawable/ic_launcher_foreground.xml: launcher icon and monochrome themed icon

Run from anywhere after changing the geometry: python3 tools/logo.py
"""

from pathlib import Path

MINT = "#66B8A6"  # Theme.accent (light)
# Logo geometry on a 24×24 grid.
BALL = (12, 11, 8.5)  # cx, cy, r
WRAPS = [(0, 22, 12.5), (0, 22, 16), (0, 22, 19.5), (25, -1, 12.5)]  # circles cut out of the ball
WRAP_WIDTH = 1.4
TAIL = "M12,19.5c3,1.6 6,1.9 10,1.2"
TAIL_WIDTH = 1.6
# Placement in the 108dp adaptive icon; the content stays inside the 66dp safe zone.
SCALE = 2.4
CENTER = (12.75, 12)


def num(v):
    return f"{v:.2f}".rstrip("0").rstrip(".")


def circle(cx, cy, r):
    return f"M{num(cx - r)},{num(cy)}a{num(r)},{num(r)} 0,1 0,{num(2 * r)},0a{num(r)},{num(r)} 0,1 0,{num(-2 * r)},0z"


def svg():
    wraps = "\n".join(f'        <circle cx="{x}" cy="{y}" r="{r}"/>' for x, y, r in WRAPS)
    cx, cy, r = BALL
    return f"""<svg xmlns="http://www.w3.org/2000/svg" width="24" height="24" viewBox="0 0 24 24">
  <!-- Generated by tools/logo.py. nøste logo: a ball of yarn with cut-out wraps and a loose end. -->
  <defs>
    <mask id="wraps">
      <rect width="24" height="24" fill="#fff"/>
      <g fill="none" stroke="#000" stroke-width="{WRAP_WIDTH}">
{wraps}
      </g>
    </mask>
  </defs>
  <circle cx="{cx}" cy="{cy}" r="{r}" fill="{MINT.lower()}" mask="url(#wraps)"/>
  <path d="{TAIL}" fill="none" stroke="{MINT.lower()}" stroke-width="{TAIL_WIDTH}" stroke-linecap="round"/>
</svg>
"""


def vector():
    # VectorDrawable has no masks: each wrap becomes a ring (two circles) that evenOdd cuts out of the
    # ball, clipped to the ball.
    ball = circle(*BALL)
    half = WRAP_WIDTH / 2
    cut = ball + "".join(circle(x, y, r + half) + circle(x, y, r - half) for x, y, r in WRAPS)
    tx = 54 - CENTER[0] * SCALE
    ty = 54 - CENTER[1] * SCALE
    return f"""<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by tools/logo.py. Launcher icon and monochrome themed icon. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="108dp"
    android:height="108dp"
    android:viewportWidth="108"
    android:viewportHeight="108">
    <group
        android:scaleX="{SCALE}"
        android:scaleY="{SCALE}"
        android:translateX="{num(tx)}"
        android:translateY="{num(ty)}">
        <group>
            <clip-path android:pathData="{ball}" />
            <path
                android:fillColor="{MINT}"
                android:fillType="evenOdd"
                android:pathData="{cut}" />
        </group>
        <path
            android:strokeColor="{MINT}"
            android:strokeWidth="{TAIL_WIDTH}"
            android:strokeLineCap="round"
            android:pathData="{TAIL}" />
    </group>
</vector>
"""


if __name__ == "__main__":
    root = Path(__file__).resolve().parent.parent
    (root / "ui/icons/logo.svg").write_text(svg())
    (root / "android/res/drawable/ic_launcher_foreground.xml").write_text(vector())
