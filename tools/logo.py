#!/usr/bin/env python3
"""Generates the Flausch logo in pink, drawn with soft lines: a ball of yarn with cat ears and the loose yarn end
curled up as the cat's tail.

Single source for:
- ui/icons/logo.svg: in the app (colorized with Theme.accent) and in the README
- android/res/drawable/ic_launcher_foreground.xml: monochrome themed launcher icon
The colored launcher icon and the store icon (the same motif embroidered on knit) come from tools/knit.py.

Run from anywhere after changing the geometry: python3 tools/logo.py
"""

from pathlib import Path

PINK = "#DF7FA5"  # Theme.accent (light)
LINE = 1.2  # stroke width of every line
# Logo geometry on a 24×24 grid; VIEW centers it in logo.svg.
VIEW = (3.4, 2.5, 20)  # x, y, size
BALL = (11.5, 12.2, 6.6)  # cx, cy, r
# Left ear as one cubic curve up to the tip and one back to the ball; the right ear is mirrored at BALL's cx.
EAR = [(5.3, 9.94), (5.3, 7.34), (5.7, 5.2), (5.8, 3.6), (7.6, 4.1), (6.8, 5.58), (8.2, 6.48)]
WRAPS = [(3, 21.2, 7.2), (3, 21.2, 9.9), (3, 21.2, 12.6), (22, 4, 9.4)]  # circles, clipped to the ball
TAIL = "M15.29,17.61C15,21.6 19.4,22.2 21.2,20.2C22.6,18.6 21.4,16.6 19.9,17.3"
# Placement in the 108dp adaptive icon; the content stays inside the 66dp safe zone.
SCALE = 2.6
CENTER = (13.4, 12.5)
STORE_ZOOM = 1.4  # the store icon has no safe zone, so the ball can be larger (tools/knit.py)


def num(v):
    return f"{v:.2f}".rstrip("0").rstrip(".")


def pt(p):
    return f"{num(p[0])},{num(p[1])}"


def circle(cx, cy, r):
    return f"M{num(cx - r)},{num(cy)}a{num(r)},{num(r)} 0,1 0,{num(2 * r)},0a{num(r)},{num(r)} 0,1 0,{num(-2 * r)},0z"


def ears():
    cx = BALL[0]
    right = [(2 * cx - x, y) for x, y in EAR]
    return "".join(f"M{pt(e[0])}C{pt(e[1])} {pt(e[2])} {pt(e[3])}C{pt(e[4])} {pt(e[5])} {pt(e[6])}" for e in (EAR, right))


def wraps():
    return "".join(circle(*w) for w in WRAPS)


def svg():
    cx, cy, r = BALL
    x, y, size = VIEW
    return f"""<svg xmlns="http://www.w3.org/2000/svg" width="24" height="24" viewBox="{num(x)} {num(y)} {num(size)} {num(size)}">
  <!-- Generated by tools/logo.py. Flausch logo: a ball of yarn with cat ears and a curled tail. -->
  <defs>
    <clipPath id="ball">
      <circle cx="{cx}" cy="{cy}" r="{r}"/>
    </clipPath>
  </defs>
  <g fill="none" stroke="{PINK.lower()}" stroke-width="{LINE}" stroke-linecap="round" stroke-linejoin="round">
    <circle cx="{cx}" cy="{cy}" r="{r}"/>
    <path d="{ears()}"/>
    <path d="{wraps()}" clip-path="url(#ball)"/>
    <path d="{TAIL}"/>
  </g>
</svg>
"""


def stroke(data, width=LINE, indent=8):
    pad = " " * indent
    return f"""{pad}<path
{pad}    android:strokeColor="{PINK}"
{pad}    android:strokeWidth="{num(width)}"
{pad}    android:strokeLineCap="round"
{pad}    android:strokeLineJoin="round"
{pad}    android:pathData="{data}" />"""


def vector():
    tx = 54 - CENTER[0] * SCALE
    ty = 54 - CENTER[1] * SCALE
    return f"""<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by tools/logo.py. Launcher icon and monochrome themed icon. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="108dp"
    android:height="108dp"
    android:viewportWidth="108"
    android:viewportHeight="108">
    <group
        android:scaleX="{SCALE}"
        android:scaleY="{SCALE}"
        android:translateX="{num(tx)}"
        android:translateY="{num(ty)}">
{stroke(circle(*BALL) + ears() + TAIL)}
        <group>
            <clip-path android:pathData="{circle(*BALL)}" />
{stroke(wraps(), indent=12)}
        </group>
    </group>
</vector>
"""


if __name__ == "__main__":
    root = Path(__file__).resolve().parent.parent
    (root / "ui/icons/logo.svg").write_text(svg())
    (root / "android/res/drawable/ic_launcher_foreground.xml").write_text(vector())
