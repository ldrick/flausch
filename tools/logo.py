#!/usr/bin/env python3
"""Generates the nøste logo in mint, drawn with soft lines: a ball of yarn with cat ears, a crochet hook behind it
and the loose yarn end curled up as the cat's tail.

Single source for:
- ui/icons/logo.svg: in the app (colorized with Theme.accent) and in the README
- android/res/drawable/ic_launcher_foreground.xml: launcher icon and monochrome themed icon

Run from anywhere after changing the geometry: python3 tools/logo.py
"""

import math
from pathlib import Path

MINT = "#66B8A6"  # Theme.accent (light)
LINE = 1.2  # stroke width of every line
# Logo geometry on a 24×24 grid.
BALL = (11.5, 12.2, 6.6)  # cx, cy, r
# Left ear as one cubic curve up to the tip and one back to the ball; the right ear is mirrored at BALL's cx.
EAR = [(5.3, 9.94), (5.3, 7.34), (5.7, 5.2), (5.8, 3.6), (7.6, 4.1), (6.8, 5.58), (8.2, 6.48)]
WRAPS = [(3, 21.2, 7.2), (3, 21.2, 9.9), (3, 21.2, 12.6), (22, 4, 9.4)]  # circles, clipped to the ball
TAIL = "M15.29,17.61C15,21.6 19.4,22.2 21.2,20.2C22.6,18.6 21.4,16.6 19.9,17.3"
HOOK = ((1.6, 21.2), (22.6, 9.6))  # handle end, head; the part behind the ball is left out
HOOK_GAP = 1.2  # space between the ball and the hook
HOOK_GRIP = (0.16, 0.32, 2.2)  # thumb rest: start and end as a fraction of the length, width
# Placement in the 108dp adaptive icon; the content stays inside the 66dp safe zone.
SCALE = 2.3
CENTER = (12.1, 12.4)


def num(v):
    return f"{v:.2f}".rstrip("0").rstrip(".")


def pt(p):
    return f"{num(p[0])},{num(p[1])}"


def circle(cx, cy, r):
    return f"M{num(cx - r)},{num(cy)}a{num(r)},{num(r)} 0,1 0,{num(2 * r)},0a{num(r)},{num(r)} 0,1 0,{num(-2 * r)},0z"


def ears():
    cx = BALL[0]
    right = [(2 * cx - x, y) for x, y in EAR]
    return "".join(f"M{pt(e[0])}C{pt(e[1])} {pt(e[2])} {pt(e[3])}C{pt(e[4])} {pt(e[5])} {pt(e[6])}" for e in (EAR, right))


def wraps():
    return "".join(circle(*w) for w in WRAPS)


def hook():
    """Shaft (without the part behind the ball) with the hook at the head, and the thumb rest."""
    (ax, ay), (bx, by) = HOOK
    length = math.hypot(bx - ax, by - ay)
    ux, uy = (bx - ax) / length, (by - ay) / length
    nx, ny = uy, -ux  # the hook opens upwards

    def at(t):
        return ax + ux * t, ay + uy * t

    cx, cy, r = BALL
    fx, fy = ax - cx, ay - cy
    b = fx * ux + fy * uy
    disc = b * b - (fx * fx + fy * fy - (r + HOOK_GAP) ** 2)
    hidden = (-b - math.sqrt(disc), -b + math.sqrt(disc)) if disc > 0 else (length, length)
    head = (bx + ux * 0.5 + nx, by + uy * 0.5 + ny)
    tip = (bx - ux * 1.5 + nx, by - uy * 1.5 + ny)
    shaft = f"M{pt(at(0))}L{pt(at(hidden[0]))}" if hidden[0] > 0 else ""
    shaft += f"M{pt(at(hidden[1]))}L{pt((bx, by))}Q{pt(head)} {pt(tip)}"
    start, end, width = HOOK_GRIP
    return shaft, f"M{pt(at(length * start))}L{pt(at(length * end))}", width


def svg():
    cx, cy, r = BALL
    shaft, grip, grip_width = hook()
    return f"""<svg xmlns="http://www.w3.org/2000/svg" width="24" height="24" viewBox="0 0 24 24">
  <!-- Generated by tools/logo.py. nøste logo: a ball of yarn with cat ears, a crochet hook and a curled tail. -->
  <defs>
    <clipPath id="ball">
      <circle cx="{cx}" cy="{cy}" r="{r}"/>
    </clipPath>
  </defs>
  <g fill="none" stroke="{MINT.lower()}" stroke-width="{LINE}" stroke-linecap="round" stroke-linejoin="round">
    <path d="{shaft}"/>
    <path d="{grip}" stroke-width="{grip_width}"/>
    <circle cx="{cx}" cy="{cy}" r="{r}"/>
    <path d="{ears()}"/>
    <path d="{wraps()}" clip-path="url(#ball)"/>
    <path d="{TAIL}"/>
  </g>
</svg>
"""


def stroke(data, width=LINE, indent=8):
    pad = " " * indent
    return f"""{pad}<path
{pad}    android:strokeColor="{MINT}"
{pad}    android:strokeWidth="{num(width)}"
{pad}    android:strokeLineCap="round"
{pad}    android:strokeLineJoin="round"
{pad}    android:pathData="{data}" />"""


def vector():
    shaft, grip, grip_width = hook()
    tx = 54 - CENTER[0] * SCALE
    ty = 54 - CENTER[1] * SCALE
    return f"""<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by tools/logo.py. Launcher icon and monochrome themed icon. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="108dp"
    android:height="108dp"
    android:viewportWidth="108"
    android:viewportHeight="108">
    <group
        android:scaleX="{SCALE}"
        android:scaleY="{SCALE}"
        android:translateX="{num(tx)}"
        android:translateY="{num(ty)}">
{stroke(shaft)}
{stroke(grip, grip_width)}
{stroke(circle(*BALL) + ears() + TAIL)}
        <group>
            <clip-path android:pathData="{circle(*BALL)}" />
{stroke(wraps(), indent=12)}
        </group>
    </group>
</vector>
"""


if __name__ == "__main__":
    root = Path(__file__).resolve().parent.parent
    (root / "ui/icons/logo.svg").write_text(svg())
    (root / "android/res/drawable/ic_launcher_foreground.xml").write_text(vector())
